import "errors"

const ModulePass = 4

type Question struct {
	Text    string
	Options [3]string
	answer  int // индекс правильного варианта
}

type Module struct {
	Title     string
	Material  []string
	Questions []Question
}

func Score(questions []Question, answers []int) (int, error) {
	if len(answers) != len(questions) {
		return 0, errors.New("ответьте на все вопросы")
	}
	score := 0
	for i, answer := range answers {
		if answer < 0 || answer >= len(questions[i].Options) {
			return 0, errors.New("ответьте на все вопросы")
		}
		if answer == questions[i].answer {
			score++
		}
	}
	return score, nil
}

